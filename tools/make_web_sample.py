"""Create the web demo's explicitly synthetic document photograph from original text."""

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont, PngImagePlugin

ROOT = Path(__file__).resolve().parents[1]


def main():
    font_path = ROOT / "web/public/fonts/manrope.ttf"

    def font(size):
        face = ImageFont.truetype(str(font_path), size)
        face.set_variation_by_axes([500])
        return face

    paper = Image.new("RGB", (680, 880), "#fcfbf7")
    draw = ImageDraw.Draw(paper)
    draw.text((54, 48), "FIELD NOTES", font=font(16), fill="#3d6650")
    draw.line((54, 88, 626, 88), fill="#a5b4a8", width=1)
    draw.text((54, 123), "A little more clarity.", font=font(39), fill="#273b30")
    draw.text((54, 191), "On slowing down and seeing the whole page", font=font(20), fill="#526459")
    lines = [
        "A good note makes room for a thought. It gives it",
        "a place to land, a shape to follow, and a reason",
        "to be remembered. The page does not have to be",
        "perfect. It only has to be readable.",
        "",
        "We collect ideas in all kinds of places: a book",
        "held open on a desk, a folded sheet in a pocket,",
        "a handwritten list beside the morning coffee.",
        "The useful part is what is written there.",
        "",
        "Give the edges a little space. Let the light fall",
        "evenly. Keep the whole page in view. A small",
        "change in perspective can make all the difference.",
    ]
    for i, line in enumerate(lines):
        draw.text((54, 259 + i * 31), line, font=font(21), fill="#333c36")
    draw.line((54, 728, 626, 728), fill="#a5b4a8", width=1)
    draw.text((54, 760), "FLATTENER / SYNTHETIC SAMPLE", font=font(14), fill="#3d6650")
    draw.text(
        (54, 792),
        "An original test document. No private information.",
        font=font(15),
        fill="#526459",
    )
    # A smooth analytic paper bend, inverted into output-photo pixels.
    height, width = 1050, 980
    yy, xx = np.mgrid[:height, :width].astype(np.float64)
    v = (yy - 80) / 830
    for _ in range(8):
        u = (xx - 158 - 48 * v) / 625
        v = (yy - 80 - 42 * np.sin(np.pi * u) - 25 * u) / 830
    valid = (u >= 0) & (u <= 1) & (v >= 0) & (v <= 1)
    px = np.clip((u * 679).round().astype(int), 0, 679)
    py = np.clip((v * 879).round().astype(int), 0, 879)
    background = np.empty((height, width, 3), np.uint8)
    for c, value in enumerate([172, 184, 174]):
        background[..., c] = np.clip(value - yy / height * 18 + xx / width * 5, 0, 255)
    shade = 1 - 0.10 * np.sin(np.pi * u) ** 4
    sampled = np.clip(np.asarray(paper)[py, px].astype(float) * shade[..., None], 0, 255)
    background[valid] = sampled[valid].astype(np.uint8)
    metadata = PngImagePlugin.PngInfo()
    metadata.add_text(
        "Source",
        "Original synthetic document generated by tools/make_web_sample.py; "
        "Manrope font under SIL OFL 1.1.",
    )
    metadata.add_text(
        "impeccable:prompt",
        "Origin: Original synthetic page authored and rendered by tools/make_web_sample.py. "
        "Analytic paper bend, original English text, Manrope under SIL OFL 1.1. No stock photo.",
    )
    Image.fromarray(background).save(ROOT / "web/public/sample.png", pnginfo=metadata)


if __name__ == "__main__":
    main()
